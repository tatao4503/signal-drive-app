import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, symlinkSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { selectDevice, parseCheckArgs, buildRestoreCommands, executeRestoration, validateSnapshot, parseInt32Property, runDeviceCheck } from '../scripts/android-device-check.mjs';
import { assertExternalKeystore, isPathWithin, publicSourcePath, signingState, exclusiveCopy } from '../scripts/build-release.mjs';

const snapshot = () => ({ rotationAuto: '1', rotationUser: '2', autoTime: 'null', fontScale: '1.15', wmSizeOverride: '720x1280', debugLogProperty: '', epochSeconds: 1_700_000_000, elapsedMs: 1000, vhal: { gear: 4, parkingBrake: 1 } });
function temporary(t) {
  const directory = mkdtempSync(path.join(tmpdir(), 'signal-tooling-'));
  t.after(() => rmSync(directory, { recursive: true, force: true }));
  return directory;
}

test('device selection refuses ambiguity and explicitly requested offline devices', () => {
  const devices = 'List of devices attached\nemulator-5580 device product:phone\nemulator-5582 device product:car\nemulator-5584 offline\n';
  assert.throws(() => selectDevice(devices), /하나로 특정/);
  assert.throws(() => selectDevice(devices, 'emulator-5584'), /연결·승인/);
  assert.throws(() => selectDevice(devices, 'missing'), /연결·승인/);
  assert.equal(selectDevice(devices, 'emulator-5582'), 'emulator-5582');
});

test('clock mutation requires explicit emulator serial before any device operation', () => {
  assert.throws(() => parseCheckArgs(['candidate.apk', 'new', '--clock']), /전용 에뮬레이터/);
  assert.throws(() => parseCheckArgs(['candidate.apk', 'new', '--serial', 'physical-device', '--clock']), /전용 에뮬레이터/);
  assert.equal(parseCheckArgs(['candidate.apk', 'new', '--serial', 'emulator-5580', '--clock']).withClock, true);
  assert.throws(() => parseCheckArgs(['candidate.apk', 'new', '--serial']), /옵션/);
});

test('cleanup restores exact overrides and elapsed wall time instead of hardcoded defaults', () => {
  const original = snapshot();
  const commands = buildRestoreCommands(original, { restoreClock: true, restoreVehicle: true, elapsedNowMs: 4500 });
  assert.equal(commands.find(x => x.label === 'device-clock').command, 'date @1700000003');
  assert.equal(commands.find(x => x.label === 'auto-time').command, 'settings delete global auto_time');
  assert.equal(commands.find(x => x.label === 'rotation-user').command, 'settings put system user_rotation 2');
  assert.equal(commands.find(x => x.label === 'font-scale').command, 'settings put system font_scale 1.15');
  assert.equal(commands.find(x => x.label === 'screen-override').command, 'wm size 720x1280');
  assert.equal(commands.find(x => x.label === 'vehicle-parking-brake').command, 'cmd car_service inject-vhal-event 0x11200402 0 true');
  assert.deepEqual(original, snapshot());
});

test('cleanup attempts every remaining setting after an individual restore failure', () => {
  const commands = buildRestoreCommands(snapshot(), { restoreClock: true, restoreVehicle: true, elapsedNowMs: 2000 });
  const attempted = [];
  const result = executeRestoration(commands, command => { attempted.push(command); if (attempted.length === 1) throw new Error('synthetic failure'); });
  assert.equal(result.ok, false);
  assert.equal(result.steps[0].ok, false);
  assert.equal(result.steps.at(-1).ok, true);
  assert.deepEqual(attempted, commands.map(x => x.command));
});

test('unsafe snapshots or unsuccessful VHAL readings cannot become cleanup commands', () => {
  assert.throws(() => validateSnapshot({ ...snapshot(), fontScale: '1; invalid' }), /글자 크기/);
  assert.throws(() => validateSnapshot({ ...snapshot(), rotationUser: '9' }), /원래 설정/);
  assert.throws(() => parseInt32Property('Property:0x11400400, status: 1, int32Values: [4]'), /정상 상태/);
  assert.equal(parseInt32Property('Property:0x11400400, status: 0, int32Values: [4]'), 4);
});

test('keystore guard resolves links and accepts outside siblings with similar prefixes', t => {
  const directory = temporary(t), source = path.join(directory, 'source'), sibling = path.join(directory, 'source-keys');
  mkdirSync(source); mkdirSync(sibling);
  const internal = path.join(source, 'key.jks'), external = path.join(sibling, 'key.jks');
  writeFileSync(internal, 'not a real keystore'); writeFileSync(external, 'not a real keystore');
  symlinkSync(internal, path.join(sibling, 'link-to-internal.jks'));
  assert.throws(() => assertExternalKeystore(source, path.join(sibling, 'link-to-internal.jks')), /작업본 밖/);
  assert.equal(assertExternalKeystore(source, external), realpathSync(external));
  assert.equal(isPathWithin(source, sibling), false);
});

test('source identity excludes credentials and generated bytecode', () => {
  for (const file of ['server/.env', 'app/private.jks', 'scripts/__pycache__/helper.pyc', 'scripts/helper.pyc', 'app/build/output.apk', 'app/build.nosync/generated/source.java', 'core/build.nosync/output.jar']) assert.equal(publicSourcePath(file), false, file);
  assert.equal(publicSourcePath('app/src/main/AndroidManifest.xml'), true);
  assert.equal(signingState({}).kind, 'none');
  assert.equal(signingState({ SIGNAL_RELEASE_STORE_FILE: 'test path only' }).kind, 'partial');
});

test('release copy preserves an existing deliverable instead of replacing it', t => {
  const directory = temporary(t), source = path.join(directory, 'candidate'), target = path.join(directory, 'existing');
  writeFileSync(source, 'new'); writeFileSync(target, 'old');
  assert.throws(() => exclusiveCopy(source, target), /EEXIST/);
  assert.equal(readFileSync(target, 'utf8'), 'old');
});

test('nonempty evidence folder is rejected before adb is queried or changed', async t => {
  const directory = temporary(t), apk = path.join(directory, 'candidate.apk'), output = path.join(directory, 'evidence');
  writeFileSync(apk, 'synthetic input only'); mkdirSync(output); writeFileSync(path.join(output, 'keep.txt'), 'original');
  await assert.rejects(runDeviceCheck([apk, output]), /덮어쓰지/);
  assert.equal(readFileSync(path.join(output, 'keep.txt'), 'utf8'), 'original');
});
